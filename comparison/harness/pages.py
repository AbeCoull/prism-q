README_START = "<!-- comparison-preview:start -->"
README_END = "<!-- comparison-preview:end -->"


def readme_block(manifest: dict, derived: dict) -> str:
    """Counts only, no simulator names: the names and the numbers live on the linked pages."""
    rows = [r for r in derived["ratios"] if r["group"] == "headline" and r["validated"]]
    comparators = len({r["comparator"] for r in rows})
    workloads_n = len({r["workload_id"] for r in rows})
    host = manifest["provenance"]["host"]
    return "\n".join(
        _wrap(
            [
                README_START,
                "",
                "![Comparator time over PRISM-Q time per workload](docs/comparison/figures/fig1-ratio-heatmap.svg)",
                "",
                f"Time ratios for {len(rows)} validated comparisons ({workloads_n} workloads, {comparators} "
                f"comparator configurations, one {host.get('cpu_model')}). The "
                "[comparison pages](https://abecoull.github.io/prism-q/comparison.html) give every row with its "
                "spread, peak memory and validation, and the "
                "[engineering report](https://abecoull.github.io/prism-q/comparison/report.html) discusses what "
                "the gaps come from and where the measurements stop.",
                "",
                README_END,
            ]
        )
    )


def update_readme(results_dir: str, readme: str) -> None:
    manifest, _ = aggregate.load(results_dir)
    with open(os.path.join(results_dir, "derived.json"), encoding="utf-8") as handle:
        derived = json.load(handle)
    with open(readme, encoding="utf-8") as handle:
        text = handle.read()
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < 0:
        raise SystemExit(f"{readme} has no {README_START} ... {README_END} block")
    text = text[:start] + readme_block(manifest, derived) + text[end + len(README_END) :]
    with open(readme, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"updated the comparison preview in {readme}")


def write(results_dir: str, docs_dir: str, landing: str | None) -> None:
    manifest, records = aggregate.load(results_dir)
    derived = aggregate.write(results_dir)
    os.makedirs(docs_dir, exist_ok=True)
    with open(os.path.join(docs_dir, "results.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(results_page(results_dir, manifest, records, derived, "./figures"))
    if landing:
        with open(landing, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(landing_page(results_dir, manifest, records, derived))
    print(f"wrote {docs_dir}/results.md" + (f" and {landing}" if landing else ""))
