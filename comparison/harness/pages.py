def _column(name: str) -> str:
    base, _, threads = name.partition("@")
    if threads:
        return f"{_column(base)} {threads} thread" + ("s" if threads != "1" else "")
    return COLUMN.get(name, aggregate.label(name))


def _ms(value: float | None) -> str:
    if value is None:
        return "n/a"
    if value < 1.0:
        return f"{value * 1000:.0f} us"
    if value >= 1000.0:
        return f"{value / 1000:.2f} s"
    if value < 10:
        return f"{value:.2f} ms"
    return f"{value:.1f} ms" if value < 100 else f"{value:.0f} ms"


def _mb(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value / 1024:.2f} GB" if value >= 1024 else f"{value:.0f} MB"


def _x(value: float) -> str:
    if value >= 100:
        return f"{value:.0f}x"
    return f"{value:.1f}x" if value >= 10 else f"{value:.2f}x"


def _span(values: list[float]) -> str:
    lo, hi = min(values), max(values)
    return _x(lo) if _x(lo) == _x(hi) else f"{_x(lo)} to {_x(hi)}"


def _and(items: list) -> str:
    words = [f"{i:,}" if isinstance(i, int) else str(i) for i in items]
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def _only(values) -> object | None:
    """The single distinct value, or None when there are none or several."""
    distinct = set(values)
    return next(iter(distinct)) if len(distinct) == 1 else None


def _wrap(lines: list[str]) -> list[str]:
    """Wrap prose paragraphs and list items at `WRAP` columns; tables, headings, HTML and code stay as they are."""
    out: list[str] = []
    fenced = False
    for line in lines:
        if line.startswith("```"):
            fenced = not fenced
        if fenced or len(line) <= WRAP or line.startswith(("|", "#", "!", "<", "```")):
            out.append(line)
            continue
        indent = "  " if line.startswith("- ") else ""
        out += textwrap.wrap(line, WRAP, subsequent_indent=indent, break_long_words=False, break_on_hyphens=False)
    return out


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out + [""]


def _html_table(header: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{html.escape(h)}</th>" for h in header)
    body = "".join("<tr>" + "".join(f"<td>{html.escape(str(c))}</td>" for c in row) + "</tr>" for row in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _figure(chart: str, kicker: str, title: str, table: str | None = None, note: str | None = None) -> list[str]:
    """One chart block: static kicker, title and table; `perf.js` fills the plot slot."""
    parts = [
        f'<figure class="pq-figure" data-chart="{chart}">',
        f'<p class="pq-kicker">{html.escape(kicker)}</p>',
        f'<p class="pq-title">{html.escape(title)}</p>',
        '<div class="pq-plot"></div>',
    ]
    if note:
        parts.append(f'<p class="pq-note">{html.escape(note)}</p>')
    if table:
        parts.append(f'<details class="pq-table"><summary>Exact numbers</summary>{table}</details>')
    parts.append("</figure>")
    return ["\n".join(parts), ""]


def _top(records: list[dict]) -> list[dict]:
    """Each simulator's record at its own top thread count."""
    top: dict[str, int] = {}
    for r in records:
        top[r["simulator"]] = max(top.get(r["simulator"], 0), r["threads"])
    return [r for r in records if r["threads"] == top[r["simulator"]]]


def _pick(records: list[dict], name: str) -> dict | None:
    """The record a section column names: `sim` at its top thread count, or `sim@T` at T threads."""
    base, _, threads = name.partition("@")
    if threads:
        return next((r for r in records if r["simulator"] == base and r["threads"] == int(threads)), None)
    return next((r for r in _top(records) if r["simulator"] == base), None)


def _status(record: dict | None) -> str | None:
    """The word a table shows instead of a time, or None when the record has a valid time."""
    if record is None or record["status"] == "skipped":
        return NOT_RUN
    if record["status"] == "not-applicable":
        return CANNOT_RUN
    if record["status"] != "ok":
        return _outcome(record)
    if (record.get("validation") or {}).get("pass") is False:
        return "invalid"
    return None


def _outcome(record: dict) -> str:
    reason = record.get("reason") or ""
    if record["status"] == "oom" and "Insufficient memory" in reason and "statevector" in reason:
        return "refused, statevector would not fit"
    return OUTCOME.get(record["status"], record["status"])


def _mark(record: dict) -> str:
    """The footnote mark of an ok record: unchecked, weakly tested, or a reference without a cross-check."""
    v = record.get("validation") or {}
    if v.get("role") == "reference":
        return "" if v.get("cross_check") else UNCROSSED
    if v.get("role") == "weakly-tested":
        return WEAK
    return "" if aggregate.validated(record) else UNCHECKED


def _legend(marks: set[str]) -> str | None:
    used = [m for m in (UNCHECKED, WEAK, UNCROSSED) if m in marks]
    return "; ".join(f"{m} {MARK_WORDS[m]}" for m in used) + "." if used else None


def _top_ratios(derived: dict) -> list[dict]:
    """Validated ratios at each peer's top thread count on its row."""
    top: dict[tuple[str, str, str], int] = defaultdict(int)
    for x in derived["ratios"]:
        key = (x["group"], x["workload_id"], x["comparator"])
        top[key] = max(top[key], x["threads"])
    return [
        x
        for x in derived["ratios"]
        if x["validated"] and x["threads"] == top[(x["group"], x["workload_id"], x["comparator"])]
    ]


def _ratios(derived: dict) -> dict[tuple[str, str, str], float]:
    """Validated ratio per (group, workload, comparator) at the row's top thread count."""
    return {(x["group"], x["workload_id"], x["comparator"]): x["ratio"] for x in _top_ratios(derived)}


def _section_rows(records: list[dict], group: str, families: tuple) -> dict[str, list[dict]]:
    by_wl: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        if r["group"] == group and r["workload"]["family"] in families:
            by_wl[r["workload"]["workload_id"]].append(r)
    order = sorted(by_wl, key=lambda k: aggregate.family_order(by_wl[k][0]["workload"]))
    return {wid: by_wl[wid] for wid in order}


def _comparison(records: list[dict], ratio: dict, section: tuple) -> tuple[list[float], str, list[str], set[str]]:
    """Ref ratios, the exact-numbers tables, the columns shown and the footnote marks used."""
    sid, _, _, group, families, sims, ref, _ = section
    rows = _section_rows(records, group, families)
    present = [s for s in sims if any(_pick(recs, s) for recs in rows.values())]
    table, detail, values, marks = [], [], [], set()
    for wid, recs in rows.items():
        line = [aggregate.row_label(recs[0]["workload"])]
        extra = [line[0]]
        for s in present:
            r = _pick(recs, s)
            extra.append(_timing_detail(r))
            if _status(r):
                line.append(_status(r))
                continue
            mark = _mark(r)
            marks.add(mark)
            if not s.startswith("prismq") and (group, wid, s) in ratio:
                line.append(f"{_ms(r['stats']['median_ms'])} ({_x(ratio[(group, wid, s)])}){mark}")
            else:
                line.append(_ms(r["stats"]["median_ms"]) + mark)
        if (group, wid, ref) in ratio:
            values.append(ratio[(group, wid, ref)])
        table.append(line)
        detail.append(extra)
    header = [_column(s) for s in present]
    if any("@" in s for s in present):
        for i, s in enumerate(present):
            threads = _only(r["threads"] for recs in rows.values() if (r := _pick(recs, s)))
            if "@" not in s and threads:
                header[i] = _column(f"{s}@{threads}")
    tables = _html_table(["Workload"] + header, table)
    tables += (
        '<p class="pq-note">Cold call, fastest warm call, the time Aer reports for itself, and the smallest '
        "shift in a marginal a sampled check detects:</p>"
    )
    tables += _html_table(["Workload"] + header, detail)
    return values, tables, present, marks - {""}


def _timing_detail(record: dict | None) -> str:
    if record is None or record["status"] != "ok":
        return _status(record) or ""
    parts = []
    first = (record.get("phases") or {}).get("first_ms")
    if first is not None:
        parts.append(f"cold {_ms(first)}")
    if record["stats"].get("min_ms") is not None:
        parts.append(f"fastest {_ms(record['stats']['min_ms'])}")
    internal = record.get("internal_ms") or []
    if internal:
        parts.append(f"internal {_ms(_median(internal))}")
    detectable = (record.get("validation") or {}).get("min_detectable")
    if detectable is not None:
        parts.append(f"detects {detectable:.2g}")
    return ", ".join(parts)


def _median(values: list[float]) -> float:
    ordered = sorted(values)
    mid = len(ordered) // 2
    return ordered[mid] if len(ordered) % 2 else (ordered[mid - 1] + ordered[mid]) / 2


def _kicker(template: str, rows: dict[str, list[dict]]) -> str:
    """Fill `{shots}`, `{block}`, `{depth}` and `{observables}` from the rows, dropping a part whose rows disagree."""
    workloads = [recs[0]["workload"] for recs in rows.values()]
    values = {
        "shots": _only(w["shots"] for w in workloads),
        "block": _only(w["params"].get("block") for w in workloads),
        "depth": _only(w["params"].get("depth") for w in workloads),
        "observables": _only(w["params"].get("observables") for w in workloads),
    }
    shown = dict(values)
    shown["shots"] = f"{values['shots']:,} shots" if values["shots"] else ""
    if values["observables"]:
        shown["observables"] = f"{values['observables']} Z and {values['observables']} ZZ"
    parts = []
    for part in template.split(" · "):
        if any("{" + k + "}" in part and v is None for k, v in values.items()):
            continue
        parts.append(part.format(**shown))
    return " · ".join(parts)


def _notes(sid: str, rows: dict[str, list[dict]], sims: list[str]) -> list[str]:
    """Section bullets the records determine."""
    recs = [r for group in rows.values() for r in group]
    notes = []
    if sid in ("stabilizer", "highshot"):
        threads = sorted({r["threads"] for r in recs if r["simulator"] == "prismq"})
        if threads:
            pairing = (
                "ratios pair Stim with the 1-thread PRISM-Q record"
                if 1 in threads
                else "no 1-thread PRISM-Q record ran, so no ratio is shown"
            )
            notes.append(f"Stim runs single-threaded; PRISM-Q runs at {_and(threads)} threads, and {pairing}.")
    if sid == "tn":
        opt = next((r["details"]["optimizer"] for r in recs if (r.get("details") or {}).get("optimizer")), None)
        if opt:
            methods = _and(opt["hyper_methods"])
            kahypar = "" if opt.get("kahypar_available") else "kahypar was unavailable, so "
            rust = (
                ", with cotengrust installed for its greedy and optimal paths"
                if opt.get("cotengrust_available")
                else ""
            )
            notes.append(f"{kahypar}cotengra searched paths with {methods} under `{opt['optlib']}`{rust}.")
            if opt.get("storage_cleared_per_call"):
                notes.append(
                    "quimb's circuit storage is cleared on every call and a fresh optimizer built for every "
                    "observable, so the contraction path search is inside every timed call."
                )
    if sid == "mpsdeep":
        skipped: dict[str, dict[int, int]] = defaultdict(dict)
        for r in recs:
            if r["status"] == "not-applicable" and r["simulator"].startswith("quimb-mps"):
                depth = r["workload"]["params"].get("depth")
                ran = [
                    x["workload"]["num_qubits"]
                    for x in recs
                    if x["simulator"] == r["simulator"]
                    and x["status"] != "not-applicable"
                    and x["workload"]["params"].get("depth") == depth
                ]
                if ran:
                    skipped[r["simulator"]][depth] = max(ran)
        for name, by_depth in skipped.items():
            limits = _and([f"{n:,} qubits at depth {d}" for d, n in sorted(by_depth.items())])
            notes.append(f"{_column(name)} runs up to {limits}; a wider row would not fit the row budget.")
    if sid in ("mps", "disjoint"):
        auto = [r for r in recs if r["simulator"] == "aer-automatic"]
        refused = [r for r in auto if _outcome(r).startswith("refused,") and r["status"] == "oom"]
        oom = [r for r in auto if r["status"] == "oom" and r not in refused]
        if refused:
            notes.append(
                f"Aer automatic refuses {len(refused)} of {len(auto)} rows before running: it picks its "
                "statevector method and reports that the state would not fit in memory."
            )
        if oom:
            notes.append(f"Aer automatic runs out of memory on {len(oom)} of {len(auto)} rows.")
    if sid in ("mps", "mpsdeep"):
        notes.append(_cutoffs(recs))
    if sid == "disjoint":
        routes: dict[str, list[int]] = defaultdict(list)
        backends = set()
        for r in recs:
            if r["simulator"] == "prismq" and r["status"] == "ok" and r.get("route"):
                routes[r["route"]].append(r["workload"]["num_qubits"])
                backends.add(r.get("resolved_backend"))
        if routes:
            backend = _only(backends)
            ordered = sorted(routes.items(), key=lambda kv: min(kv[1]))
            by_route = [f"`{route}` at {_and(sorted(set(ns)))} qubits" for route, ns in ordered]
            lead = f"PRISM-Q resolves `{backend}`, with route " if backend else "PRISM-Q takes route "
            notes.append(lead + _and(by_route) + ".")
    if any(r["workload"]["family"] == "qft" for r in recs):
        control = any(r["simulator"] == QFT_CONTROL for r in recs)
        notes.append(
            "QFT rows take their gate list from PRISM-Q's `qft_circuit` generator, and PRISM-Q recognises that "
            "expansion and runs it as one FFT block"
            + ("; the control below reruns PRISM-Q with `PRISM_NO_QFT_BLOCK=1`, gate by gate." if control else ".")
        )
    return notes + _shared_notes(recs, sims)


def _cutoffs(recs: list[dict]) -> str:
    """The truncation each MPS simulator applies besides its bond cap, from the records where they carry it."""
    aer = _only(
        (r.get("details") or {}).get("truncation_threshold") for r in recs if r["simulator"].startswith("aer-mps")
    )
    quimb = _only((r.get("details") or {}).get("cutoff") for r in recs if r["simulator"].startswith("quimb-mps"))
    parts = [f"PRISM-Q drops singular values at or below {runners.PRISMQ_MPS_SVD_EPSILON:g} of the largest"]
    if any(r["simulator"].startswith("aer-mps") for r in recs):
        parts.append(
            f"Aer runs with `matrix_product_state_truncation_threshold` {aer:g}"
            if aer is not None
            else "Aer runs with its default `matrix_product_state_truncation_threshold`"
        )
    if quimb is not None:
        same = " (the value of Aer's threshold)" if aer is not None and quimb == aer else ""
        parts.append(f"quimb's CircuitMPS runs with `cutoff` {quimb:g}{same}")
    return "Truncation besides the bond cap: " + "; ".join(parts) + "."


def _shared_notes(recs: list[dict], sims: list[str]) -> list[str]:
    """Bullets every section derives the same way: timed outputs, cold calls, check power and references."""
    notes = []
    mode = _only(r["workload"]["mode"] for r in recs)
    shown = [
        s for s in dict.fromkeys(name.partition("@")[0] for name in sims) if any(r["simulator"] == s for r in recs)
    ]
    recs = [r for r in recs if r["simulator"] in shown]
    outputs = [(s, runners.timed_output(s, mode)) for s in shown] if mode else []
    if outputs and all(o for _, o in outputs):
        by_output: dict[str, list[str]] = defaultdict(list)
        for s, o in outputs:
            by_output[o].append(_column(s))
        notes.append(
            "The timed call ends at the simulator's own result: "
            + "; ".join(f"{_and(names)}, a {o}" for o, names in by_output.items())
            + "."
        )
    slow = []
    for r in recs:
        first = (r.get("phases") or {}).get("first_ms")
        median = (r.get("stats") or {}).get("median_ms")
        if r["simulator"].startswith("prismq") or r["status"] != "ok" or not first or not median:
            continue
        if median > WARM_OVER_COLD * first:
            slow.append(
                f"{_column(r['simulator'])} {aggregate.row_label(r['workload'])} "
                f"({_ms(first)} cold, {_ms(median)} warm)"
            )
    if slow:
        notes.append(
            f"Warm median more than {round((WARM_OVER_COLD - 1) * 100)}% above the cold call: " + _and(slow) + "."
        )
    detectable = defaultdict(list)
    for r in recs:
        v = r.get("validation") or {}
        if r["status"] == "ok" and v.get("min_detectable") is not None:
            detectable[r["simulator"]].append(v["min_detectable"])
    if detectable:
        spans = [
            f"{_column(s)} {_detect_span(v)}" for s, v in sorted(detectable.items(), key=lambda kv: kv[0] != "prismq")
        ]
        notes.append(
            "Smallest shift in a marginal the sampled check detects: " + _and(spans) + f"; checks above "
            f"{validate.WEAK_DETECTABLE:g} are marked weakly tested."
        )
    uncrossed = sorted(
        {
            aggregate.row_label(r["workload"])
            for r in recs
            if (r.get("validation") or {}).get("role") == "reference" and not r["validation"].get("cross_check")
        },
        key=lambda label: label,
    )
    if uncrossed:
        notes.append(
            f"{len(uncrossed)} rows take their reference vector from one simulator with no cross-check by a second."
        )
    return notes + _settings(recs)


def _settings(recs: list[dict]) -> list[str]:
    """Peer options the records carry in their details, one bullet per simulator family."""
    notes = []
    fused: dict[int, set[int]] = defaultdict(set)
    for r in recs:
        size = (r.get("details") or {}).get("max_fused_gate_size")
        if r["simulator"] == "qsim" and size is not None:
            fused[size].add(r["workload"]["num_qubits"])
    if fused:
        spans = [f"{size} at {_and(sorted(ns))} qubits" for size, ns in sorted(fused.items())]
        notes.append("qsim runs with `max_fused_gate_size` " + _and(spans) + ".")
    aer = [
        r["details"]
        for r in recs
        if r["simulator"].startswith(("aer-mps", "aer-automatic")) and (r.get("details") or {}).get("mps_lapack")
    ]
    if aer:
        notes.append(
            "Aer's matrix product state method runs with `mps_lapack=True` and `mps_omp_threads` equal to the "
            "thread count."
        )
    return notes


def _detect_span(values: list[float]) -> str:
    lo, hi = min(values), max(values)
    return f"{lo:.2g}" if f"{lo:.2g}" == f"{hi:.2g}" else f"{lo:.2g} to {hi:.2g}"


def _qft_control(records: list[dict]) -> list[str]:
    """PRISM-Q with and without QFT recognition beside the fp64 reference, on the headline QFT rows."""
    rows = _section_rows(records, "headline", ("qft",))
    if not any(r["simulator"] == QFT_CONTROL for recs in rows.values() for r in recs):
        return []
    sims = ["prismq", QFT_CONTROL, "aer-statevector"]
    table = []
    for recs in rows.values():
        line = [aggregate.row_label(recs[0]["workload"])]
        for s in sims:
            r = _pick(recs, s)
            line.append(_status(r) or _ms(r["stats"]["median_ms"]) + _mark(r))
        table.append(line)
    return _table(["QFT control", *(_column(s) for s in sims)], table)


def _qubit_span(records: list[dict], group: str, families: tuple) -> str:
    ns = sorted(
        {r["workload"]["num_qubits"] for r in records if r["group"] == group and r["workload"]["family"] in families}
    )
    return f"{ns[0]:,} to {ns[-1]:,} qubits" if len(ns) > 1 else f"{ns[0]:,} qubits"


def _summary(records: list[dict], ratio: dict, derived: dict) -> list[str]:
    if not ratio:
        return []
    tops = _top_ratios(derived)
    peer_threads: dict[str, set[int]] = defaultdict(set)
    for x in tops:
        peer_threads[x["comparator"]].add(x["threads"])
    precision = {r["simulator"]: r.get("precision") for r in records}
    table = []
    for section in SECTIONS:
        _, heading, _, group, families, sims, _, _ = section
        wids = set(_section_rows(records, group, families))
        for s in sims:
            if s.partition("@")[0].startswith("prismq"):
                continue
            picked = [x for x in tops if x["group"] == group and x["workload_id"] in wids and x["comparator"] == s]
            if not picked:
                continue
            threads = _and(sorted({x["threads"] for x in picked}))
            peer = precision.get(s) or "n/a"
            shown = "fp32 peer, PRISM-Q fp64" if peer == "single" else f"{peer}, PRISM-Q double"
            table.append([heading, _column(s), shown, threads, str(len(picked)), _span([x["ratio"] for x in picked])])
    counts = defaultdict(list)
    for peer, threads in sorted(peer_threads.items()):
        counts[_and(sorted(threads))].append(_column(peer))
    kicker = "Thread counts, PRISM-Q matched to the peer: " + "; ".join(
        f"{_and(names)} at {threads} thread" + ("" if threads == "1" else "s") for threads, names in counts.items()
    )
    title = "Peer median time over PRISM-Q median time, per section and peer"
    header = ["Section", "Peer", "Precision", "Threads", "Rows", "Range"]
    return _figure("summary", kicker, title, _html_table(header, table))


def _scaling(derived: dict, records: list[dict], host: dict) -> list[str]:
    rows = [row for row in derived.get("scaling") or [] if row["speedup_vs_1"]]
    if not rows:
        return []
    top = max(row["threads"] for row in rows)
    labels = {r["workload"]["workload_id"]: aggregate.row_label(r["workload"]) for r in records}
    at_top: dict[str, dict[str, float]] = defaultdict(dict)
    for row in rows:
        if row["threads"] == top:
            at_top[row["workload_id"]][row["simulator"]] = row["speedup_vs_1"]
    table = [[labels[w]] + [_x(v[s]) if s in v else "-" for s in SCALING] for w, v in sorted(at_top.items())]
    own = [v["prismq"] for v in at_top.values() if "prismq" in v]
    title = (
        f"PRISM-Q time at 1 thread is {_span(own)} its time at {top} threads"
        if own
        else f"Time at 1 thread over time at {top} threads"
    )
    cores = ""
    if host.get("physical_cores") and host.get("logical_cores"):
        cores = f"{host['physical_cores']} physical cores, {host['logical_cores']} hardware threads; "
    lines = ["## Thread scaling", ""]
    lines += [f"- {cores}{'rows' if cores else 'Rows'} below {top} threads are timed without an output check.", ""]
    lines += _figure(
        "threads",
        f"Strong scaling · 1 to {top} threads",
        title,
        _html_table([f"{top} threads over 1"] + [_column(s) for s in SCALING], table),
    )
    return lines


def _dispatch(derived: dict, records: list[dict]) -> list[str]:
    labels = {r["workload"]["workload_id"]: aggregate.row_label(r["workload"]) for r in records}
    table, regrets = [], []
    declined: dict[str, list[str]] = defaultdict(list)
    for d in sorted(
        derived.get("dispatch") or [], key=lambda d: aggregate.family_order(_wl(records, d["workload_id"]))
    ):
        for name, v in d["forced"].items():
            if v.get("status") not in (None, "not-applicable"):
                declined[name.partition(":")[2]].append(v["status"])
        regret = (d.get("auto_over_best") or {}).get("ratio")
        if regret:
            regrets.append(regret)
        best = (d.get("best_forced") or "").partition(":")[2]
        table.append(
            [
                labels[d["workload_id"]],
                f"{d.get('auto_backend')}, {_ms(d.get('auto_median_ms'))}",
                f"{best}, {_ms(d.get('best_forced_median_ms'))}" if best else "n/a",
                _x(regret) if regret else "n/a",
            ]
        )
    notes = []
    for name, statuses in sorted(declined.items()):
        kinds = ", ".join(f"{statuses.count(k)} {OUTCOME.get(k, k)}" for k in sorted(set(statuses)))
        notes.append(f"{name} ({kinds})")
    if not table:
        return []
    title = (
        f"Automatic dispatch takes {_span(regrets)} the time of the fastest forced backend on {len(regrets)} rows"
        if regrets
        else "Automatic dispatch against the fastest forced backend"
    )
    lines = ["## Automatic dispatch", ""]
    lines += ["- Each row also runs with every PRISM-Q backend forced by hand, on the same circuit.", ""]
    lines += _figure(
        "dispatch",
        "Auto against every forced backend",
        title,
        _html_table(["Workload", "Automatic choice", "Fastest forced backend", "Automatic / fastest"], table),
        ("Forced backends without a valid output: " + "; ".join(notes) + ".") if notes else None,
    )
    return lines


def _wl(records: list[dict], wid: str) -> dict:
    return next(r["workload"] for r in records if r["workload"]["workload_id"] == wid)


def _accuracy(records: list[dict]) -> list[str]:
    rows = {r["simulator"]: r for r in records if r["group"] == "accuracy" and r["status"] == "ok"}
    caps = sorted({int(n.rsplit("-", 1)[1]) for n in rows if n.startswith("prismq:mps-")})
    shared = [c for c in caps if f"aer-mps:{c}" in rows]
    if not shared:
        return []
    workload = _only(aggregate.row_label(r["workload"]) for r in rows.values())

    def cell(name: str) -> list[str]:
        r = rows.get(name)
        if r is None:
            return ["-", "-"]
        tvd = (r.get("validation") or {}).get("tvd")
        return [_ms(r["stats"]["median_ms"]), f"{tvd:.2g}" if tvd is not None else "n/a"]

    table = [[str(c)] + cell(f"prismq:mps-{c}") + cell(f"aer-mps:{c}") for c in caps]
    top = shared[-1]
    p, a = cell(f"prismq:mps-{top}"), cell(f"aer-mps:{top}")
    title = f"At bond cap {top}, PRISM-Q MPS reaches distance {p[1]} in {p[0]}; Aer MPS reaches {a[1]} in {a[0]}"
    return _figure(
        "bondcap",
        "MPS bond cap against accuracy" + (f" · {workload}" if workload else ""),
        title,
        _html_table(["Bond cap", "PRISM-Q MPS", "Distance", "Aer MPS", "Distance"], table),
    )


def _sweep(records: list[dict]) -> list[str]:
    """Bond cap against the largest expectation-value error on the wider registers."""
    rows = [r for r in records if r["group"] == "bondsweep" and r["status"] == "ok"]
    if not rows:
        return []
    by_n: dict[int, dict[str, dict]] = defaultdict(dict)
    for r in rows:
        by_n[r["workload"]["num_qubits"]][r["simulator"]] = r
    caps = sorted({c for r in rows if (c := _cap(r["simulator"])) is not None})
    present = [(prefix, name) for prefix, name in SWEEP if any(r["simulator"].startswith(prefix) for r in rows)]

    def cell(r: dict | None) -> list[str]:
        if r is None:
            return ["-", "-"]
        err = (r.get("validation") or {}).get("max_abs_error")
        return [_ms(r["stats"].get("median_ms")), f"{err:.2g}" if err is not None else "n/a"]

    header = ["Qubits", "Bond cap"]
    for _, name in present:
        header += [name, "Largest error"]
    table = []
    for n, sims in sorted(by_n.items()):
        for c in caps:
            line = [f"{n:,}", str(c)]
            for prefix, _ in present:
                line += cell(sims.get(f"{prefix}{c}"))
            table.append(line)
    widest = max(by_n)
    exact = [
        c
        for c in caps
        if all(
            ((by_n[widest].get(f"{p}{c}") or {}).get("validation") or {}).get("max_abs_error", 1.0) <= 1e-8
            for p, _ in present
            if f"{p}{c}" in by_n[widest]
        )
    ]
    depth = _only(r["workload"]["params"].get("depth") for r in rows)
    title = f"Largest error in Z and adjacent ZZ against the exact value, {_and(sorted(by_n))} qubits"
    if exact:
        title += f"; every simulator is within 1e-8 from bond cap {exact[0]} at {widest} qubits"
    return _figure(
        "sweep",
        "MPS bond cap against expectation-value error" + (f" · brickwork depth {depth}" if depth else ""),
        title,
        _html_table(header, table),
        "Error is the largest absolute difference from the cone reference over every Z and adjacent ZZ value.",
    )


