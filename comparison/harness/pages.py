def data(manifest: dict, records: list[dict], suite: dict | None) -> dict:
    """The chart data: one compact row per observation, failures included with their reason."""
    rows = []
    for r in records:
        if r["group"] == "seeds":
            continue
        w, s, st = r["workload"], r["simulator"], r.get("stats") or {}
        status = r["status"]
        if status == "ok" and not aggregate.valid_or_unvalidated(r):
            status = "invalid"
        v = r.get("validation") or {}
        row = {
            "group": r["group"],
            "workload": w["workload_id"],
            "label": aggregate.row_label(w),
            "family": w["family"],
            "qubits": w["num_qubits"],
            "mode": w["mode"],
            "shots": w.get("shots"),
            "gates": w.get("num_operations"),
            "depth": w["params"].get("depth"),
            "layout": w["params"].get("layout"),
            "measured": w["params"].get("measured"),
            "simulator": s,
            "name": aggregate.label(s) if not s.startswith("prismq:") else "PRISM-Q " + s.partition(":")[2],
            "method": _method(s),
            "precision": r.get("precision"),
            "threads": r["threads"],
            "status": status,
            "checked": r.get("validation") is not None,
            "reason": _reason(r.get("reason") or "") or None,
            "median_ms": _round(st.get("median_ms")),
            "p25_ms": _round(st.get("p25_ms")),
            "p75_ms": _round(st.get("p75_ms")),
            "n": st.get("n"),
            "peak_rss_mb": _round(r.get("peak_rss_mb")),
            "resolved_backend": r.get("resolved_backend"),
            "bond_cap": _cap(s),
            "tvd": _round(v.get("tvd")),
        }
        rows.append({k: val for k, val in row.items() if val is not None})
    host = manifest["provenance"]["host"]
    return {
        "host": {"cpu": _host_line(host), "ram_gb": host.get("ram_gb")},
        "versions": {aggregate.label(k): v.get("version") for k, v in manifest["simulators"].items()},
        "observations": rows,
        "suite": suite,
    }


def write(results_dir: str, docs_dir: str) -> None:
    manifest, records = aggregate.load(results_dir)
    derived = aggregate.write(results_dir)
    os.makedirs(docs_dir, exist_ok=True)
    suite_path = os.path.join(docs_dir, "suite.json")
    suite = None
    if os.path.exists(suite_path):
        with open(suite_path, encoding="utf-8") as handle:
            suite = json.load(handle)
    with open(os.path.join(docs_dir, "index.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(page(results_dir, manifest, records, derived, suite))
    with open(os.path.join(docs_dir, "data.js"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by `python comparison/matrix.py report`. Do not edit by hand.\n")
        handle.write("window.PRISM_PERF = ")
        json.dump(data(manifest, records, suite), handle, separators=(",", ":"), sort_keys=True)
        handle.write(";\n")
    print(f"wrote {docs_dir}/index.md and {docs_dir}/data.js")
