def _ms(value: float | None) -> str:
    if value is None:
        return "n/a"
    if value < 1.0:
        return f"{value * 1000:.0f} us"
    if value >= 1000.0:
        return f"{value / 1000:.2f} s"
    return f"{value:.1f} ms"


def _mb(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value / 1024:.2f} GB" if value >= 1024 else f"{value:.0f} MB"


def _ratio(r: dict | None) -> str:
    if not r:
        return "n/a"
    text = f"{r['ratio']:.2f}x"
    if r.get("ci95_low") is not None:
        text += f" ({r['ci95_low']:.2f} to {r['ci95_high']:.2f})"
    return text


def _cell(record: dict) -> str:
    status = record["status"]
    if status == "not-applicable":
        return "not applicable"
    if status != "ok":
        return status
    v = record.get("validation") or {}
    s = record["stats"]
    text = f"{_ms(s.get('median_ms'))} [{_ms(s.get('p25_ms'))}, {_ms(s.get('p75_ms'))}]"
    if v.get("pass") is False:
        text += " INVALID"
    elif v.get("role") == "reference":
        text += " (reference)"
    return text


def _wrap(lines: list[str]) -> list[str]:
    """Wrap prose paragraphs and list items at `WRAP` columns; tables, headings and code stay as they are."""
    out: list[str] = []
    fenced = False
    for line in lines:
        if line.startswith("```"):
            fenced = not fenced
        if fenced or len(line) <= WRAP or line.startswith(("|", "#", "!", "<!--", "```")):
            out.append(line)
            continue
        indent = "  " if line.startswith("- ") else ""
        out += textwrap.wrap(line, WRAP, subsequent_indent=indent, break_long_words=False, break_on_hyphens=False)
    return out


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out


