def _ratio_summary(derived: dict) -> list[list[str]]:
    per: dict[str, list] = defaultdict(list)
    for r in derived["ratios"]:
        if r["group"] == "headline" and r["validated"]:
            per[r["comparator"]].append(r)
    rows = []
    for name, rs in sorted(per.items()):
        ratios = sorted(r["ratio"] for r in rs)
        mid = len(ratios) // 2
        median = ratios[mid] if len(ratios) % 2 else 0.5 * (ratios[mid - 1] + ratios[mid])
        families = ", ".join(sorted({r["family"] for r in rs}))
        rows.append([f"`{name}`", str(len(rs)), families, f"{median:.2f}x", f"{ratios[0]:.2f}x", f"{ratios[-1]:.2f}x"])
    return rows


