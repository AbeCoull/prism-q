def _family_tables(records: list[dict], group: str, title: str) -> list[str]:
    rows = [r for r in records if r["group"] == group]
    if not rows:
        return []
    out = [f"## {title}", ""]
    by_wl: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_wl[r["workload"]["workload_id"]].append(r)
    order = sorted(by_wl, key=lambda k: _order_key(by_wl[k][0]["workload"]))
    precision_groups = [
        ("fp64 and exact", lambda r: r["precision"] != "single"),
        ("fp32", lambda r: r["precision"] == "single"),
    ]
    for label, pick in precision_groups:
        sims = sorted({r["simulator"] for r in rows if pick(r)}, key=lambda s: (s != "prismq", s))
        if not sims or sims == ["prismq"]:
            continue
        if label == "fp32":
            sims = ["prismq"] + [s for s in sims if s != "prismq"]
        out.append(f"### {label} comparators")
        out.append("")
        out.append(
            "Median per call with [p25, p75]; the ratio column is the comparator's median over PRISM-Q's, "
            "with its bootstrap 95% interval."
        )
        out.append("")
        header = ["Workload", "Gates"] + [f"`{s}`" for s in sims] + [f"ratio `{s}`" for s in sims if s != "prismq"]
        table_rows = []
        for wid in order:
            recs = {r["simulator"]: r for r in by_wl[wid] if r["threads"] == max(x["threads"] for x in by_wl[wid])}
            if not any(pick(r) for r in recs.values() if r["simulator"] != "prismq"):
                continue
            base = recs.get("prismq")
            line = [f"`{wid}`", str(by_wl[wid][0]["workload"]["num_operations"])]
            for s in sims:
                line.append(_cell(recs[s]) if s in recs else "not run")
            for s in sims:
                if s == "prismq":
                    continue
                r = recs.get(s)
                if r and base and aggregate.valid(r) and aggregate.valid(base):
                    line.append(_ratio(stats.ratio(r["samples_ms"], base["samples_ms"])))
                else:
                    line.append("n/a")
            table_rows.append(line)
        if table_rows:
            out += _table(header, table_rows) + [""]
    return out


def _order_key(wl: dict) -> tuple:
    order = ["rcs", "qft", "qv", "clifford", "lowent", "disjoint", "midcircuit", "sampling"]
    fam = wl["family"]
    return (
        order.index(fam) if fam in order else 99,
        wl["params"].get("depth", 0),
        str(wl["params"].get("layout")),
        wl["num_qubits"],
        wl["shots"],
        str(wl["params"].get("measured")),
        wl["params"].get("seed", 0),
    )


def _memory_table(records: list[dict]) -> list[str]:
    rows = [r for r in records if r["group"] == "headline" and r["status"] == "ok" and r.get("peak_rss_mb")]
    if not rows:
        return []
    by_wl: dict[str, dict[str, float]] = defaultdict(dict)
    wl_meta = {}
    for r in rows:
        by_wl[r["workload"]["workload_id"]][r["simulator"]] = r["peak_rss_mb"]
        wl_meta[r["workload"]["workload_id"]] = r["workload"]
    sims = sorted({r["simulator"] for r in rows}, key=lambda s: (s != "prismq", s))
    order = sorted(by_wl, key=lambda k: _order_key(wl_meta[k]))
    table = [[f"`{w}`"] + [_mb(by_wl[w].get(s)) for s in sims] for w in order]
    return (
        [
            "## Peak memory",
            "",
            "Peak working set of the measuring process (and its children), headline thread count.",
            "",
        ]
        + _table(["Workload"] + [f"`{s}`" for s in sims], table)
        + [""]
    )


def _failures(records: list[dict]) -> list[str]:
    rows = [r for r in records if r["status"] not in ("ok",)]
    invalid = [
        r
        for r in records
        if r["status"] == "ok"
        and (r.get("validation") or {}).get("pass") is False
        and (r.get("validation") or {}).get("pass_required", True)
    ]
    out = ["## Failures, refusals and skipped cells", ""]
    if not rows and not invalid:
        return out + ["Every listed cell ran and validated.", ""]
    table = []
    for r in sorted(rows + invalid, key=lambda r: (_order_key(r["workload"]), r["simulator"], r["threads"])):
        reason = (r.get("reason") or "").replace("|", "/")[:140]
        status = r["status"] if r in rows else "invalid output"
        if status == "invalid output":
            v = r["validation"]
            reason = "; ".join(v.get("failures") or []) or f"TVD {v.get('tvd')}"
        table.append([f"`{r['workload']['workload_id']}`", f"`{r['simulator']}`", str(r["threads"]), status, reason])
    return out + _table(["Workload", "Simulator", "Threads", "Outcome", "Detail"], table) + [""]


def _dispatch(derived: dict) -> list[str]:
    rows = derived.get("dispatch") or []
    if not rows:
        return []
    table = []
    for d in rows:
        regret = d.get("auto_over_best")
        declined = sorted(k.split(":")[1] for k, v in d["forced"].items() if "status" in v)
        table.append(
            [
                f"`{d['workload_id']}`",
                f"{d.get('auto_backend')} via {d.get('auto_route')}",
                _ms(d.get("auto_median_ms")),
                f"{d.get('plan_median_us'):.1f} us" if d.get("plan_median_us") is not None else "n/a",
                f"`{d.get('best_forced')}`" if d.get("best_forced") else "n/a",
                _ms(d.get("best_forced_median_ms")),
                _ratio(regret),
                ", ".join(declined) or "none",
            ]
        )
    return (
        [
            "## Automatic dispatch against forced backends",
            "",
            "`auto / best` is the automatic run's median over the fastest validated forced backend. "
            "Plan time is the median of 21 calls to `Simulate::plan`, the dispatch decision alone.",
            "",
        ]
        + _table(
            [
                "Workload",
                "Auto picked",
                "Auto median",
                "Plan time",
                "Fastest forced",
                "Its median",
                "auto / best",
                "Backends that declined or timed out",
            ],
            table,
        )
        + [""]
    )


