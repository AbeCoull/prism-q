"""Documentation pages generated from a matrix results directory.

`write` produces the landing page and `results.md` from `manifest.json`,
`observations.jsonl` and `derived.json` only; rerunning it on the same directory
reproduces them byte for byte. The pages report numbers and attach no verdict.
"""

from __future__ import annotations

import os
import re
import textwrap
from collections import defaultdict

from . import aggregate

FRAMING = "Time per call for the same circuits in PRISM-Q and other simulators, on one desktop."
RATIO_NOTE = "Ratio = comparator median time / PRISM-Q median time."
GENERATED = "<!-- Generated by `python comparison/matrix.py report`. Do not edit by hand. -->"
WRAP = 90
DENSE = ["prismq", "aer-statevector", "quest", "spinoza", "qip", "aer-statevector-f32", "qsim"]
STRUCTURED = ["prismq", "stim", "aer-mps", "aer-automatic"]
SAMPLED = ["prismq", "aer-statevector", "aer-statevector-f32", "qsim"]
SCALING = ["prismq", "aer-statevector", "qsim", "quest"]
OUTCOME = {"oom": "out of memory", "timeout": "timeout", "crash": "crash", "error": "refused"}
COLUMN = {
    "aer-statevector": "Aer",
    "aer-statevector-f32": "Aer fp32",
    "aer-automatic": "Aer auto",
    "qsim": "qsim fp32",
}
FAMILY = {"lowent": "shallow", "disjoint": "disconnected", "rcs": "rcs", "qft": "qft", "qv": "qv"}


def _column(name: str) -> str:
    return COLUMN.get(name, aggregate.label(name))


def _ms(value: float | None) -> str:
    if value is None:
        return "n/a"
    if value < 1.0:
        return f"{value * 1000:.0f} us"
    if value >= 1000.0:
        return f"{value / 1000:.2f} s"
    if value < 10:
        return f"{value:.2f} ms"
    return f"{value:.1f} ms" if value < 100 else f"{value:.0f} ms"


def _mb(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value / 1024:.2f} GB" if value >= 1024 else f"{value:.0f} MB"


def _x(value: float) -> str:
    if value >= 100:
        return f"{value:.0f}x"
    return f"{value:.1f}x" if value >= 10 else f"{value:.2f}x"


def _wrap(lines: list[str]) -> list[str]:
    """Wrap prose paragraphs and list items at `WRAP` columns; tables, headings and code stay as they are."""
    out: list[str] = []
    fenced = False
    for line in lines:
        if line.startswith("```"):
            fenced = not fenced
        if fenced or len(line) <= WRAP or line.startswith(("|", "#", "!", "[!", "<!--", "```")):
            out.append(line)
            continue
        indent = "  " if line.startswith("- ") else ""
        out += textwrap.wrap(line, WRAP, subsequent_indent=indent, break_long_words=False, break_on_hyphens=False)
    return out


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out + [""]


def _figure(rel: str, stem: str, alt: str) -> list[str]:
    """A figure that links to its own SVG, so a click opens it at full size."""
    return [f"[![{alt}]({rel}/{stem}.svg)]({rel}/{stem}.svg)", ""]


def _top(records: list[dict]) -> list[dict]:
    top = max(r["threads"] for r in records)
    return [r for r in records if r["threads"] == top]


def _status(record: dict) -> str | None:
    if record["status"] == "not-applicable":
        return "-"
    if record["status"] != "ok":
        return OUTCOME.get(record["status"], record["status"])
    if (record.get("validation") or {}).get("pass") is False:
        return "invalid"
    return None


def _comparison(records: list[dict], group: str, mode: str, sims: list[str], derived: dict) -> list[str]:
    rows = [r for r in records if r["group"] == group and r["workload"]["mode"] == mode]
    by_wl: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_wl[r["workload"]["workload_id"]].append(r)
    ratio = {(x["workload_id"], x["comparator"]): x["ratio"] for x in derived["ratios"] if x["group"] == group}
    present = [s for s in sims if any(r["simulator"] == s for r in rows)]
    table = []
    for wid in sorted(by_wl, key=lambda k: aggregate.family_order(by_wl[k][0]["workload"])):
        recs = {r["simulator"]: r for r in _top(by_wl[wid])}
        line = [aggregate.row_label(by_wl[wid][0]["workload"])]
        for s in present:
            r = recs.get(s)
            if r is None:
                line.append("-")
            elif _status(r):
                line.append(_status(r))
            elif s != "prismq" and (wid, s) in ratio:
                line.append(f"{_ms(r['stats']['median_ms'])} ({_x(ratio[(wid, s)])})")
            else:
                line.append(_ms(r["stats"]["median_ms"]))
        table.append(line)
    return _table(["Workload"] + [_column(s) for s in present], table)


def _scaling(derived: dict, records: list[dict]) -> list[str]:
    labels = {r["workload"]["workload_id"]: aggregate.row_label(r["workload"]) for r in records}
    at_top: dict[str, dict[str, float]] = defaultdict(dict)
    for row in derived.get("scaling") or []:
        if row["threads"] == 8 and row["speedup_vs_1"]:
            at_top[row["workload_id"]][row["simulator"]] = row["speedup_vs_1"]
    table = [[labels[w]] + [_x(v[s]) if s in v else "-" for s in SCALING] for w, v in sorted(at_top.items())]
    return _table(["Speedup, 8 threads over 1"] + [_column(s) for s in SCALING], table)


def _dispatch(derived: dict, records: list[dict]) -> list[str]:
    labels = {r["workload"]["workload_id"]: aggregate.row_label(r["workload"]) for r in records}
    table = []
    declined: dict[str, list[str]] = defaultdict(list)
    for d in sorted(
        derived.get("dispatch") or [], key=lambda d: aggregate.family_order(_wl(records, d["workload_id"]))
    ):
        for name, v in d["forced"].items():
            if v.get("status") not in (None, "not-applicable"):
                declined[name.partition(":")[2]].append(v["status"])
        regret = (d.get("auto_over_best") or {}).get("ratio")
        best = (d.get("best_forced") or "").partition(":")[2]
        table.append(
            [
                labels[d["workload_id"]],
                f"{d.get('auto_backend')}, {_ms(d.get('auto_median_ms'))}",
                f"{best}, {_ms(d.get('best_forced_median_ms'))}" if best else "n/a",
                _x(regret) if regret else "n/a",
            ]
        )
    out = _table(["Workload", "Automatic choice", "Fastest forced backend", "Automatic / fastest"], table)
    notes = []
    for name, statuses in sorted(declined.items()):
        kinds = ", ".join(f"{statuses.count(k)} {OUTCOME.get(k, k)}" for k in sorted(set(statuses)))
        notes.append(f"{name} ({kinds})")
    if notes:
        out += ["Forced backends without a valid output: " + "; ".join(notes) + ".", ""]
    return out


def _wl(records: list[dict], wid: str) -> dict:
    return next(r["workload"] for r in records if r["workload"]["workload_id"] == wid)


def _accuracy(records: list[dict]) -> list[str]:
    rows = {r["simulator"]: r for r in records if r["group"] == "accuracy" and r["status"] == "ok"}
    caps = sorted({int(n.rsplit("-", 1)[1]) for n in rows if n.startswith("prismq:mps-")})

    def cell(name: str) -> list[str]:
        r = rows.get(name)
        if r is None:
            return ["-", "-"]
        tvd = (r.get("validation") or {}).get("tvd")
        return [_ms(r["stats"]["median_ms"]), f"{tvd:.2g}" if tvd is not None else "n/a"]

    table = [[str(c)] + cell(f"prismq:mps-{c}") + cell(f"aer-mps:{c}") for c in caps]
    return _table(["Bond cap", "PRISM-Q MPS", "Distance", "Aer MPS", "Distance"], table)


def _memory(records: list[dict]) -> list[str]:
    rows = [
        r
        for r in records
        if r["group"] == "headline"
        and r["workload"]["family"] == "rcs"
        and r["workload"]["params"].get("depth") == 10
        and r["status"] == "ok"
    ]
    by_n: dict[int, dict[str, float]] = defaultdict(dict)
    for r in rows:
        by_n[r["workload"]["num_qubits"]][r["simulator"]] = r["peak_rss_mb"]
    present = [s for s in DENSE if any(s in v for v in by_n.values())]
    table = [[f"rcs {n}q d10"] + [_mb(v.get(s)) for s in present] for n, v in sorted(by_n.items())]
    return _table(["Peak working set"] + [_column(s) for s in present], table)


def _correctness(records: list[dict]) -> list[str]:
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in records:
        v = r.get("validation")
        if not v or r["status"] != "ok" or not v.get("pass_required", True):
            continue
        outcome = v.get("role") or {True: "pass", False: "fail", None: "untested"}[v.get("pass")]
        counts[r["workload"]["mode"]][outcome] += 1
    dense, sampled = counts["probs"], counts["counts"]
    lines = [
        f"- Dense: {dense['pass']} of {dense['pass'] + dense['fail']} within tolerance of the fp64 reference.",
        f"- Sampled: {sampled['pass']} of {sampled['pass'] + sampled['fail']} passed; {sampled['too-few-shots']} "
        "under 100 shots checked on deterministic bits only.",
    ]
    failures = _failures(records)
    if failures:
        lines += ["", "Cells without a valid timing:", ""] + failures
    return lines + [""]


def _failures(records: list[dict]) -> list[str]:
    groups: dict[tuple[str, str], dict] = {}
    for r in records:
        status = _status(r)
        if status in (None, "-") or r["group"] in ("dispatch", "accuracy"):
            continue
        if status == "invalid":
            detail = f"distance {r['validation'].get('tvd'):.2g} from the reference"
        elif r["status"] == "timeout":
            detail = f"past the {r['policy']['timeout_s']:.0f} s timeout"
        else:
            detail = _reason(r.get("reason") or "")
        entry = groups.setdefault((r["simulator"], status), {"detail": detail, "workloads": []})
        label = aggregate.row_label(r["workload"])
        if label not in entry["workloads"]:
            entry["workloads"].append(label)
    table = [
        [aggregate.label(sim), status, _workload_list(e["workloads"]), e["detail"]]
        for (sim, status), e in sorted(groups.items(), key=lambda kv: (kv[0][0] != "prismq", kv[0]))
    ]
    return _table(["Simulator", "Outcome", "Workloads", "Detail"], table)[:-1] if table else []


def _workload_list(labels: list[str]) -> str:
    if len(labels) <= 3:
        return ", ".join(labels)
    counts: dict[str, int] = defaultdict(int)
    for label in labels:
        counts[FAMILY.get(label.split()[0], label.split()[0])] += 1
    return ", ".join(f"{n} {family}" for family, n in counts.items()) + " rows"


def _reason(text: str) -> str:
    code = re.fullmatch(r"exit (\d+)", text)
    if code and int(code.group(1)) > 2**31:
        return f"exit 0x{int(code.group(1)):08X}"
    text = re.sub(r"^(RuntimeError: ERROR: +\[Experiment 0\] |simulation error: )", "", text)
    return text.split(". ")[0].replace("|", "/")[:90]


def _setup(manifest: dict, records: list[dict]) -> list[str]:
    prov = manifest["provenance"]
    host, tool, py = prov["host"], prov["toolchain"], prov["python"]
    rows = [
        ["Host", _host_line(host)],
        ["PRISM-Q", f"{manifest['simulators']['prismq'].get('version')}, rustc {tool.get('rustc')}, `parallel`"],
        ["Python", py.get("version")],
        ["Commit", f"`{(tool.get('git_sha') or '')[:10]}`"],
        ["Runs", f"`{manifest['run_id']}` and {len(manifest.get('supplementary_runs', []))} supplementary runs"],
    ]
    seen = {r["simulator"].partition(":")[0] for r in records}
    for name, s in manifest["simulators"].items():
        if name in seen and name != "prismq":
            rows.append([aggregate.label(name), f"{s.get('version') or 'n/a'}, {s['precision']}"])
    return _table(["Item", "Value"], rows)


def _host_line(host: dict) -> str:
    cpu = re.sub(r"\((R|TM)\)|CPU @.*", "", host.get("cpu_model") or "").replace("Intel Core", "Intel Core ")
    cpu = " ".join(cpu.split())
    return f"{cpu}, {host.get('physical_cores')} cores, {host.get('logical_cores')} threads, {host.get('os')}"


def results_page(results_dir: str, manifest: dict, records: list[dict], derived: dict, fig: str) -> str:
    lines = [
        "# Benchmark Matrix: Results",
        "",
        GENERATED,
        "",
        f"{FRAMING} {RATIO_NOTE} Cells: median time (ratio). Raw data and spreads: "
        f"`comparison/results/{os.path.basename(results_dir)}/`.",
        "",
    ]
    lines += _figure(fig, "ratio-heatmap", "Comparator time over PRISM-Q time per workload")
    lines += ["## Dense circuits", ""] + _comparison(records, "headline", "probs", DENSE, derived)
    lines += ["## Structured circuits", ""] + _comparison(records, "headline", "counts", STRUCTURED, derived)
    lines += ["## Sampling", ""] + _comparison(records, "sampling", "counts", SAMPLED, derived)
    lines += ["## Thread scaling", ""] + _figure(fig, "thread-scaling", "Speedup over one thread")
    lines += _scaling(derived, records)
    lines += ["## Automatic dispatch", ""] + _figure(fig, "dispatch", "Automatic dispatch against forced backends")
    lines += _dispatch(derived, records)
    lines += ["## Accuracy under a bond cap", "", "rcs 20q d10; distance from the exact vector.", ""]
    lines += _accuracy(records)
    lines += ["## Peak memory", ""] + _memory(records)
    lines += ["## Correctness", ""] + _correctness(records)
    lines += ["## Setup", ""] + _setup(manifest, records)
    return "\n".join(_wrap(lines)).rstrip() + "\n"


def _ratio_summary(derived: dict) -> list[list[str]]:
    per: dict[str, list[float]] = defaultdict(list)
    for r in derived["ratios"]:
        if r["group"] == "headline" and r["validated"]:
            per[r["comparator"]].append(r["ratio"])
    rows = []
    for name, values in sorted(per.items(), key=lambda kv: aggregate.label(kv[0])):
        values.sort()
        mid = len(values) // 2
        median = values[mid] if len(values) % 2 else 0.5 * (values[mid - 1] + values[mid])
        rows.append([aggregate.label(name), str(len(values)), _x(median), f"{_x(values[0])} to {_x(values[-1])}"])
    return rows


def landing_page(results_dir: str, manifest: dict, records: list[dict], derived: dict) -> str:
    host = manifest["provenance"]["host"]
    lines = [
        "# Comparative Measurements",
        "",
        GENERATED,
        "",
        f"{FRAMING} {_host_line(host)}, CPU only.",
        "",
    ]
    lines += _figure("./comparison/figures", "ratio-heatmap", "Comparator time over PRISM-Q time per workload")
    lines += [RATIO_NOTE, ""]
    lines += _table(["Comparator", "Workloads", "Median ratio", "Range"], _ratio_summary(derived))
    lines += [
        "- [Results](./comparison/results.md): every table.",
        "- [Report](./comparison/report.md): findings and limits.",
        "- [Methodology](./comparison/methodology.md): workloads, timing, validation, rerunning.",
        "- [Probability-vector run](./comparison/probability-vector.md): the 0.33.0 comparison.",
    ]
    return "\n".join(_wrap(lines)).rstrip() + "\n"


def write(results_dir: str, docs_dir: str, landing: str | None) -> None:
    manifest, records = aggregate.load(results_dir)
    derived = aggregate.write(results_dir)
    os.makedirs(docs_dir, exist_ok=True)
    with open(os.path.join(docs_dir, "results.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(results_page(results_dir, manifest, records, derived, "./figures"))
    if landing:
        with open(landing, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(landing_page(results_dir, manifest, records, derived))
    print(f"wrote {docs_dir}/results.md" + (f" and {landing}" if landing else ""))
