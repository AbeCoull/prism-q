def _fusion(results_dir: str) -> list[str]:
    path = os.path.join(results_dir, "fusion.json")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as handle:
        counts = json.load(handle)
    rows = [
        [
            f"`{wid}`",
            str(c["input_instructions"]),
            str(c["fused_instructions"]),
            ", ".join(f"{k} {v}" for k, v in c["kinds"].items()),
        ]
        for wid, c in sorted(counts.items())
    ]
    return (
        [
            "## PRISM-Q fused instruction counts",
            "",
            "Instructions left after the statevector fusion pass (`compare_runner fusion`, written by "
            "`matrix.py fusion-counts`). On a state larger than cache each one is roughly one sweep over memory. "
            "Recognition of an exact QFT as a single FFT block happens later, at dispatch, and is not counted here.",
            "",
        ]
        + _table(["Workload", "Gates in", "Instructions after fusion", "Kinds"], rows)
        + [""]
    )


def _validation_summary(records: list[dict]) -> list[str]:
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in records:
        v = r.get("validation")
        if not v or r["status"] != "ok" or not v.get("pass_required", True):
            continue
        outcome = v.get("role") or {True: "pass", False: "fail", None: "untested"}[v.get("pass")]
        counts[r["workload"]["mode"]][outcome] += 1
    repro = [r for r in records if r.get("reproducible") is not None]
    rep_ok = sum(1 for r in repro if r["reproducible"])
    lines = ["## Correctness", ""]
    for mode, c in sorted(counts.items()):
        if mode == "probs":
            what = "dense outputs within tolerance of their row's fp64 reference vector"
            extra = f"; {c['reference']} were the reference" if c["reference"] else ""
        else:
            what = "sampled outputs passing every per-statistic test"
            extra = (
                f"; {c['too-few-shots']} had too few shots to test beyond their deterministic bits"
                if c["too-few-shots"]
                else ""
            )
        tested = c["pass"] + c["fail"]
        lines.append(f"- {c['pass']} of {tested} {what}{extra}.")
    lines.append(
        f"- {rep_ok} of {len(repro)} seeded observations returned identical output on every call "
        "(seed reproducibility)."
    )
    lines.append("")
    return lines


